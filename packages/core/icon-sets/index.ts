/**
 * An icon id string. The available icons are runtime data (see {@link iconIds}
 * and each set's manifest), so this is a plain string rather than a literal
 * union of every catalog id. Each consumer that needs a tight, checked set of
 * ids generates its own union scoped to what it uses (the editor chrome `Icon`
 * primitive and the factory export `IconProps["icon"]`).
 */
export type IconId = string

