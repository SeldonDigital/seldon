/**
 * Display label for an icon id. Drops the set prefix and title-cases the
 * suffix, so `carbon-accumulationIce` reads `Accumulation Ice`. Ids whose
 * label is not a plain title case are listed in {@link iconLabelOverrides}.
 */
export function getIconLabel(iconId: string): string {
  const override = iconLabelOverrides[iconId]
  if (override) return override

  const dash = iconId.indexOf("-")
  const suffix = dash < 0 ? iconId : iconId.slice(dash + 1)
  const spaced = suffix.replace(/([a-z0-9])([A-Z])/g, "$1 $2")

  return spaced.charAt(0).toUpperCase() + spaced.slice(1)
}

