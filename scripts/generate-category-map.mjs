/**
 * Writes a vendor `category-map.ts` from the set manifest, the per-vendor
 * `category-overrides.ts`, and the shared keyword table in
 * `constants/category-keywords.ts`. Category order per id: override, then the
 * first keyword whose token appears in the id, then the default category.
 *
 * Called by `scripts/generate-icons.mjs` after it writes the data file. Seldon
 * keeps its folder-derived map from `scripts/generate-mappings.ts`.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.dirname(scriptDir)
const catalogDir = path.join(repoRoot, "packages/core/icon-sets/catalog")
const constantsDir = path.join(repoRoot, "packages/core/icon-sets/constants")

const DEFAULT_CATEGORY_PATH = "miscellaneous/miscellaneous"

const SET_PREFIX = { material: "material", carbon: "carbon", lucide: "lucide" }

/** Parses `{ tokens: ["a","b"], path: "x/y" }` rows from the keyword table. */
function readKeywords() {
  const source = fs.readFileSync(path.join(constantsDir, "category-keywords.ts"), "utf8")
  const body = source.slice(source.indexOf("categoryKeywords"))
  const rows = []
  for (const m of body.matchAll(/\{\s*tokens:\s*\[([^\]]*)\],\s*path:\s*"([^"]+)"\s*\}/g)) {
    const tokens = [...m[1].matchAll(/"([^"]+)"/g)].map((t) => t[1].toLowerCase())
    rows.push({ tokens, path: m[2] })
  }
  return rows
}

/** Parses `"id": "path",` rows from a vendor overrides file. */
function readOverrides(folder) {
  const p = path.join(catalogDir, folder, "category-overrides.ts")
  const overrides = {}
  if (!fs.existsSync(p)) return overrides
  const source = fs.readFileSync(p, "utf8")
  for (const m of source.matchAll(/"([^"]+)":\s*"([^"]+)"\s*,/g)) overrides[m[1]] = m[2]
  return overrides
}

function readManifestIds(folder, prefix) {
  const source = fs.readFileSync(path.join(catalogDir, folder, "index-all.ts"), "utf8")
  const array = source.slice(source.indexOf(`${folder}AllIconIds`))
  const escaped = prefix.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
  const pattern = new RegExp(`"(${escaped}-[^"]+)"`, "g")
  return [...array.matchAll(pattern)].map((m) => m[1])
}

function categorize(id, prefix, overrides, keywords) {
  if (overrides[id]) return overrides[id]
  const suffix = id.slice(prefix.length + 1).toLowerCase()
  for (const { tokens, path: categoryPath } of keywords) {
    if (tokens.some((token) => suffix.includes(token))) return categoryPath
  }
  return DEFAULT_CATEGORY_PATH
}

/** Regenerates `catalog/<set>/category-map.ts`. Returns the written path. */
export function writeCategoryMap(setName) {
  const prefix = SET_PREFIX[setName]
  if (!prefix) throw new Error(`Unknown set "${setName}" for category map.`)

  const ids = readManifestIds(setName, prefix)
  const overrides = readOverrides(setName)
  const keywords = readKeywords()

  const entries = ids.map((id) => [id, categorize(id, prefix, overrides, keywords)])
  entries.sort(([idA, pathA], [idB, pathB]) =>
    pathA !== pathB ? pathA.localeCompare(pathB) : idA.localeCompare(idB),
  )

  const lines = entries.map(([id, p]) => `  "${id}": "${p}" as IconCategoryPath,`)
  const out = `/**
 * Auto-generated icon category mapping for ${setName} icon set
 * Generated by: scripts/generate-icons.mjs (keyword table + category-overrides.ts)
 * DO NOT EDIT MANUALLY - adjust constants/category-keywords.ts or ${setName}/category-overrides.ts
 */
import type { IconId } from "@seldon/core/icon-sets"

import type { IconCategoryPath } from "../../constants/categories"

export const iconCategoryMapping: Partial<Record<IconId, IconCategoryPath>> = {
${lines.join("\n")}
} as const
`
  const mapPath = path.join(catalogDir, setName, "category-map.ts")
  fs.writeFileSync(mapPath, out)
  return mapPath
}
